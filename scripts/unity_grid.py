"""Prepare the standalone GridGame project or compare real PlayMode runs with the CLI."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT / "examples/unity/GridGame"
DATA = ROOT / "examples/data"
ADAPTER = ROOT / "examples/AiNative.GridGame.Hosting"
RUNNER = ROOT / "examples/AiNative.Examples.Runner"

# Unity's Mono profile provides the remaining framework/facade assemblies.
PLUGINS = (
    "AiNative.Core", "AiNative.Hosting", "AiNative.GridGame", "AiNative.GridGame.Hosting",
    "System.Text.Json", "System.Text.Encodings.Web", "System.IO.Pipelines", "Microsoft.Bcl.AsyncInterfaces",
    "System.Runtime.CompilerServices.Unsafe",
)


def sync_package(source, project):
    packages = project / "Packages"
    target = packages / source.name
    if packages.resolve() != project.resolve() / "Packages" or target.resolve() != packages.resolve() / source.name:
        raise ValueError(f"Expected a local embedded package in {project}")

    def contents(directory):
        return {p.relative_to(directory): p.read_bytes() for p in directory.rglob("*") if p.is_file()}

    if target.is_dir() and contents(target) == contents(source):
        return
    # Stage outside the project on the same volume. A failed copy never changes the active package.
    with tempfile.TemporaryDirectory(dir=project.parent, prefix=".ainative-upm-") as tmp:
        staged, previous = Path(tmp) / "new", Path(tmp) / "previous"
        shutil.copytree(source, staged)
        if target.exists():
            target.rename(previous)
        try:
            staged.rename(target)
        except OSError:
            if previous.exists():
                previous.rename(target)
            raise


def prepare():
    subprocess.run(["dotnet", "restore", str(ADAPTER), "--locked-mode"], cwd=ROOT, check=True)
    target = PROJECT / "Assets/Plugins/AiNative"
    target.mkdir(parents=True, exist_ok=True)
    expected = {name + ".dll" for name in PLUGINS}
    extra = {path.name for path in target.glob("*.dll")} - expected
    if extra:
        raise ValueError(f"Unexpected Editor plugins in {target}: {sorted(extra)}")
    with tempfile.TemporaryDirectory() as publish:
        subprocess.run(["dotnet", "publish", str(ADAPTER), "-c", "Release", "--no-restore",
                        "-o", publish], cwd=ROOT, check=True)
        for filename in sorted(expected):
            source, dest = Path(publish) / filename, target / filename
            if not dest.exists() or source.read_bytes() != dest.read_bytes():
                shutil.copyfile(source, dest)
    # Only retire files generated by the previous Editor-only preparation step.
    legacy = PROJECT / "Assets/Editor/Plugins"
    for filename in expected:
        for name in (filename, filename + ".meta"):
            (legacy / name).unlink(missing_ok=True)
    for directory in (legacy, legacy.parent):
        if directory.is_dir() and not any(directory.iterdir()):
            directory.rmdir()
            directory.with_suffix(".meta").unlink(missing_ok=True)
    sync_package(ROOT / "packages/com.ainative.unity", PROJECT)
    for name in ("grid.scenario.json", "grid.commands.json"):
        source = DATA / name
        bundled = PROJECT / "Assets/StreamingAssets" / name
        bundled.parent.mkdir(parents=True, exist_ok=True)
        if not bundled.exists() or bundled.read_bytes() != source.read_bytes():
            shutil.copyfile(source, bundled)


def run_play_tests(output):
    # The native Test Runner needs a graphical Game view for ScreenCapture. The usual
    # batch CLI does not render one. Discover the pinned binary using the Unity CLI.
    inventory = subprocess.check_output(["unity", "editors", "--installed", "--format", "json"])
    version = (PROJECT / "ProjectSettings/ProjectVersion.txt").read_text().splitlines()[0].split()[1]
    editor = next((entry["location"] for entry in json.loads(inventory)["data"]["items"]
                   if entry["version"] == version), None)
    if not editor:
        raise RuntimeError(f"Install Unity Editor {version} to run PlayMode verification.")
    results = {}
    with tempfile.TemporaryDirectory(prefix="ainative-play-") as work:
        project = Path(work) / "GridGame"
        for directory in ("Assets", "Packages", "ProjectSettings"):
            shutil.copytree(PROJECT / directory, project / directory)
        settings = project / "ProjectSettings/EditorSettings.asset"
        original = settings.read_text(encoding="utf-8")
        for reload in ("on", "off"):
            report = output / ("reload-" + reload)
            report.mkdir()
            options = "0" if reload == "on" else "1"
            configured = re.sub(r"(?m)^  m_EnterPlayModeOptionsEnabled: \d+$", "  m_EnterPlayModeOptionsEnabled: 1", original)
            configured = re.sub(r"(?m)^  m_EnterPlayModeOptions: \d+$", "  m_EnterPlayModeOptions: " + options, configured)
            settings.write_text(configured, encoding="utf-8")
            xml = report / "playmode.xml"
            env = {**os.environ, "AINATIVE_GRID_INPUTS": str(output), "AINATIVE_GRID_EVIDENCE": str(report),
                   "AINATIVE_DOMAIN_RELOAD": reload}
            subprocess.run([editor, "-projectPath", str(project), "-runTests", "-testPlatform", "PlayMode",
                            "-testResults", str(xml), "-logFile", str(report / "editor.log")],
                           env=env, cwd=ROOT, timeout=360, check=True)
            cases = ET.parse(xml).findall(".//test-case")
            required = {"FastPresentationMatchesActualOperations", "SlowPresentationMatchesActualOperations",
                        "BoardAndHudFinishMatchAndReleaseOnRestartAndUnload",
                        "MovementAndHitFeedbackUseRenderedFramesWithoutExtraTicks",
                        "FixedPumpRetainsDebtDuringPauseAndPublishesOrderedInputsOnce",
                        "FailedCandidatePreservesActiveFrameUntilSuccessfulReplacement",
                        "BrokenOldCleanupReleasesCandidateAndAllowsFreshStart"}
            names = {case.get("name") for case in cases}
            if not required <= names or any(case.get("result") != "Passed" for case in cases):
                raise RuntimeError(f"Incomplete PlayMode acceptance, see {xml}")
            results["domainReload-" + reload] = sorted(names)
            if not (report / "game-tick-2.png").is_file():
                raise RuntimeError(f"Missing Game view screenshot in {report}")
        cycles = output / "play-cycles.xml"
        subprocess.run([editor, "-projectPath", str(project), "-runTests", "-testPlatform", "EditMode",
                        "-testFilter", "PlayCycleTests", "-testResults", str(cycles), "-logFile",
                        str(output / "play-cycles.log")], cwd=ROOT, timeout=240, check=True)
        repeated = ET.parse(cycles).findall(".//test-case")
        if len(repeated) != 1 or repeated[0].get("result") != "Passed":
            raise RuntimeError(f"Play re-entry failed, see {cycles}")
        results["reentry"] = repeated[0].get("name")
    return results


def verify(output):
    output.mkdir(parents=True, exist_ok=False)
    scene, commands = (output / name for name in ("grid.scenario.json", "grid.commands.json"))
    for path in (scene, commands):
        shutil.copyfile(DATA / path.name, path)
    subprocess.run(["dotnet", "restore", str(RUNNER), "--locked-mode"], cwd=ROOT, check=True)
    subprocess.run(["dotnet", "build", str(RUNNER), "-c", "Release", "--no-restore"], cwd=ROOT, check=True)
    runner = RUNNER / "bin/Release/net10.0/AiNative.Examples.Runner.dll"

    def cli(name, args, code, exit_code=0):
        proc = subprocess.run(["dotnet", str(runner), *args], cwd=ROOT, capture_output=True, timeout=60)
        (output / f"{name}.stdout.json").write_bytes(proc.stdout)
        (output / f"{name}.stderr.txt").write_bytes(proc.stderr)
        result = json.loads(proc.stdout)
        if proc.returncode != exit_code or result["code"] != code:
            raise RuntimeError(f"{name}: exit={proc.returncode}, code={result['code']}, see {output}")
        return result

    # The Editor receives only the input files. It cannot read a CLI baseline that does not yet exist.
    play_tests = run_play_tests(output)
    baseline = output / "cli.replay.json"
    run = cli("run", ["run", "--scenario", scene, "--seed", "42", "--commands", commands, "--replay-out", baseline], "RunCompleted")
    summary = {"unityProject": PROJECT.relative_to(ROOT).as_posix(),
               "inputs": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in (scene, commands)},
               "seed": 42, "accepted": run["accepted"], "rejected": run["rejected"],
               "winner": run["observation"]["winner"], "playTests": play_tests, "comparisons": {}}
    ticks = [cp for cp in run["checkpoints"] if cp["result"]["kind"] == "tick"]
    summary["tickHashes"] = {cp["runtime"]["tick"]: cp["stateHash"] for cp in ticks}
    if len(ticks) != 8 or (run["accepted"], run["rejected"], summary["winner"]) != (6, 1, "A"):
        raise RuntimeError("CLI did not complete the expected match")
    expected_count = len(run["checkpoints"]) + 1
    for reload in ("on", "off"):
        for speed in ("fast", "slow"):
            report = output / ("reload-" + reload)
            name = f"{reload}-{speed}"
            replay = report / f"play-{speed}.replay.json"
            compared = cli("compare-" + name, ["compare", "--expected", baseline, "--actual", replay], "HostTracesMatched")
            if compared["comparedCheckpoints"] != expected_count:
                raise RuntimeError(f"{name}: incomplete comparison")
            components = json.loads(replay.read_bytes())["initialSnapshot"]["environment"]["components"]
            for plugin in PLUGINS:
                file = PROJECT / "Assets/Plugins/AiNative" / (plugin + ".dll")
                if components.get(plugin) != hashlib.sha256(file.read_bytes()).hexdigest():
                    raise RuntimeError(f"{name}: unexpected loaded assembly {plugin}")
            summary["comparisons"][name] = {"code": compared["code"], "checkpoints": compared["comparedCheckpoints"],
                "frames": json.loads((report / f"play-{speed}.frames.json").read_bytes())}

    # Change only a legal business error in a copy to prove the comparison detects a result-only divergence.
    editor = json.loads((output / "reload-on/play-fast.replay.json").read_bytes())
    summary["unityEnvironment"] = editor["initialSnapshot"]["environment"]
    summary["cliEnvironment"] = json.loads(baseline.read_bytes())["initialSnapshot"]["environment"]
    rejection = next(cp for cp in editor["checkpoints"] if any(
        not item["accepted"] for item in cp["result"].get("inputs", [])))
    rejection["result"]["inputs"][0]["error"] = "Blocked"
    changed = output / "changed-error.replay.json"
    changed.write_text(json.dumps(editor), encoding="utf-8")
    divergent = cli("compare-changed", ["compare", "--expected", baseline, "--actual", changed], "CheckpointMismatch", 3)
    if (divergent["location"]["operationIndex"] != rejection["operationIndex"]
            or divergent["divergence"][0]["path"] != "$.result.inputs[0].error"):
        raise RuntimeError("compare failed to locate the changed rejection")
    summary["negativeControl"] = {"code": divergent["code"], "operationIndex": rejection["operationIndex"],
                                  "tick": rejection["runtime"]["tick"], "difference": divergent["divergence"][0]}
    (output / "summary.json").write_bytes((json.dumps(summary, ensure_ascii=False, indent=2) + "\n").encode("utf-8"))
    print(f"{len(ticks)} ticks, {expected_count} checkpoints, all four PlayMode traces matched CLI. Evidence: {output}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("prepare", "verify"))
    parser.add_argument("--output", type=Path, help="new evidence directory (required for verify)")
    args = parser.parse_args()
    if args.action == "verify" and args.output is None:
        parser.error("verify requires --output")
    prepare()
    if args.action == "verify":
        verify(args.output.resolve())


if __name__ == "__main__":
    main()
